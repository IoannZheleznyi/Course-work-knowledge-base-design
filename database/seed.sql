-- 3. Статьи: одна статья для каждой специи

INSERT INTO articles (
    title,
    description,
    content,
    source_name,
    source_url,
    spice_id
)
SELECT
    'Описание специи: ' || spices.name,
    spices.description,
    spices.name || '. ' || spices.description ||
        ' Страна происхождения: ' || COALESCE(spices.origin, 'не указана') ||
        '. Применение в кулинарии: ' || COALESCE(spices.usage, 'не указано'),
    'База знаний SpiceSearch',
    'https://ru.wikipedia.org/',
    spices.id
FROM spices
WHERE NOT EXISTS (
    SELECT 1
    FROM articles
    WHERE articles.spice_id = spices.id
);


